const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),ts=require('typescript');
const js=ts.transpileModule(fs.readFileSync('src/radar/vault.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const m={exports:{}};vm.runInNewContext(js,{module:m,exports:m.exports,require,Date,JSON,Math,Set,Map,Number});
const {auditLearning,exportResearch,importResearch,mergeResearch}=m.exports;
const make=(id,status='PENDING',tick=1000)=>({id,symbol:'BTCUSDT',frame:'1h',direction:'LONG',createdAt:10000,entry:100,stop:95,targets:[105,110,115],initialVotes:{'5m':'LONG','1h':'LONG','4h':'UNKNOWN'},contextCaptured:true,volumeRatio:1.1,status,tpReached:status==='TARGET'?3:0,lastCandleTime:tick,closedAt:status==='TARGET'?10200:undefined,reason:'scenario'});
const ledger={version:1,startedAt:9999,records:[make('x')]};
const backup=exportResearch(ledger,null,10002);
const parsed=importResearch(backup);
assert.equal(parsed.payload.learning.records.length,1);
assert.throws(()=>importResearch(backup.replace('"entry": 100','"entry": 101')),/сумма/);
assert.equal(auditLearning(ledger).waiting,1);
const completed={version:1,startedAt:9999,records:[make('x','TARGET',10400)]};
const merged=mergeResearch(ledger,null,importResearch(exportResearch(completed,null,10401)));
assert.equal(merged.updated,1);assert.equal(merged.learning.records[0].status,'TARGET');
assert.equal(mergeResearch(merged.learning,null,parsed).learning.records[0].status,'TARGET');
const second={version:1,startedAt:9999,records:[{...make('y'),createdAt:9995}]};
assert.equal(mergeResearch(ledger,null,importResearch(exportResearch(second,null,10003))).added,1);
const different={version:1,startedAt:9999,records:[{...make('x'),stop:90}]};
assert.throws(()=>mergeResearch(ledger,null,importResearch(exportResearch(different,null,10003))),/Несовместимые/);
const conflict={version:1,startedAt:9999,records:[make('x','STOP',10600)]};
assert.throws(()=>mergeResearch(completed,null,importResearch(exportResearch(conflict,null,10601))),/разных итоговых/);
assert.throws(()=>importResearch(JSON.stringify({...JSON.parse(backup),checksum:'00000000'})),/сумма/);
console.log('APEX Vault tests PASS: checksum, merge, no downgrades, conflict refusal');
