const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),ts=require('typescript');
function load(p,req=require){
 const js=ts.transpileModule(fs.readFileSync(p,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
 const m={exports:{}};vm.runInNewContext(js,{module:m,exports:m.exports,require:req,Date,Map,Set,Math,Number,Array,JSON});
 return m.exports;
}
const core=load('src/radar/research-core.ts');
const C=load('src/radar/core-coverage.ts',id=>id==='./research-core'?core:require(id));
const t=Date.UTC(2026,10,6,10,0);
let ledger=C.openCoreCoverage(null,t);
assert.equal(ledger.version,1);assert.equal(ledger.samples.length,0);
const observations=core.CORE_SYMBOLS.map(symbol=>({symbol,lastTick:t,framesReady:true}));
let one=C.recordCoreCoverage(ledger,observations,t+3000);
assert.equal(one.samples.length,1);
assert.equal(one.samples[0].ready,5);
assert.equal(C.recordCoreCoverage(one,observations,t+4000),one,'same-minute identical status is stable');
let partial=C.recordCoreCoverage(one,observations.slice(0,3),t+60000);
assert.equal(partial.samples[1].fresh,3);
assert.equal(partial.samples[1].ready,3);
let gap=C.recordCoreCoverage(partial,observations.map(x=>({...x,lastTick:t+180000})),t+180000);
const report=C.coreCoverageReport(gap,t+180000);
assert.equal(report.expectedSlots,4);
assert.equal(report.observedSlots,3);
assert.equal(report.missingSlots,1,'unobserved minute is missing, not imputed');
assert.equal(report.readySlots,2);
assert.equal(report.readyPct,50);
assert.equal(report.observedPct,75);
const revived=C.openCoreCoverage(JSON.stringify(gap),t+180000);
assert.equal(revived.samples.length,3);
assert.equal(C.recordCoreCoverage(revived,[],t+180000).samples.at(-1).ready,0,'stale or absent cannot count as complete');
const skew=C.recordCoreCoverage(ledger,[{symbol:'BTCUSDT',lastTick:t+60000,framesReady:true}],t+1000);
assert.equal(skew.samples[0].fresh,0,'future market tick excluded');
const market={watched:5,eligible:5,assets:core.CORE_SYMBOLS.map(symbol=>({symbol,category:'quiet',verifiedFrames:3}))};
assert(C.strictCorePulse(market));
assert.equal(C.strictCorePulse({...market,eligible:4}),undefined);
assert.equal(C.strictCorePulse({...market,assets:market.assets.map((a,i)=>i? a:{...a,verifiedFrames:2})}),undefined);
assert.equal(C.strictCorePulse({...market,assets:market.assets.map((a,i)=>i? a:{...a,symbol:'OTHER'})}),undefined);
const S=load('src/radar/context-study.ts');
const r={cohort:'fixed-core-v1',direction:'LONG',marketContext:{version:1,source:'fixed-core-v1',regime:'up',watched:5,eligible:5}};
assert.equal(S.classifyContext(r),'missing','legacy core data lacking complete-source marker excluded');
r.marketContext.quality='full-core-3tf-v1';
assert.equal(S.classifyContext(r),'with-pulse');
r.marketContext.eligible=4;
assert.equal(S.classifyContext(r),'missing','incomplete core context excluded');
const app=fs.readFileSync('src/App.tsx','utf8');
assert(app.includes('strictCorePulse(summarizePulse(fixed,quality,t))'));
assert(app.includes('recordCoreCoverage'));
assert(app.includes("document.hidden"),'screen-hidden samples must not be credited');
assert(app.includes("label:'Статистика'"));
console.log('APEX 4.2 CORE data coverage PASS: fixed universe, complete snapshot, gaps, stale/future rejection, persistence');
