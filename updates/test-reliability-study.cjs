const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),ts=require('typescript');
const js=ts.transpileModule(fs.readFileSync('src/radar/reliability-study.ts','utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS}}).outputText;
const m={exports:{}};vm.runInNewContext(js,{module:m,exports:m.exports,Math,Number});
const {evidenceReport,wilson95}=m.exports;
assert.equal(wilson95(0,0),null);
assert.equal(wilson95(10,5),null);
const mk=(kind,tp3,stop)=>({kind,title:kind,tp3,stop,total:tp3+stop,waiting:0,active:0,expired:0,cancelled:0,evaluated:tp3+stop,tp3Share:null});
const report=(a,b)=>({groups:[mk('with-pulse',...a),mk('against-pulse',...b),mk('missing',0,0)]});
let out=evidenceReport(report([2,1],[1,2]));
assert.equal(out.rows[0].rate,null);assert.equal(out.comparison,'insufficient');
out=evidenceReport(report([15,15],[11,19]));
assert.equal(out.rows[0].level,'exploratory');assert.equal(out.comparison,'insufficient');
out=evidenceReport(report([26,24],[24,26]));
assert.equal(out.rows[0].level,'observed');assert.equal(out.comparison,'overlap');
out=evidenceReport(report([90,10],[10,90]));
assert.equal(out.comparison,'separated');
assert(out.rows[0].lower>out.rows[1].upper);
console.log('APEX 3.7 reliability study tests PASS: no tiny-sample rate, Wilson interval, cautious comparison');
