const assert=require('node:assert/strict');
const fs=require('node:fs'),ts=require('typescript');
const source=fs.readFileSync('src/radar/assistant-demo.ts','utf8');
const compiled=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS},reportDiagnostics:true});
assert.equal(compiled.diagnostics?.length||0,0,'valid demo assistant TypeScript syntax');
const obj={exports:{}};
new Function('exports','module','require',compiled.outputText)(obj.exports,obj,()=>{throw Error('Unexpected runtime dependency')});
const A=obj.exports,F=300_000,t=1_000_000_000;
const scenario=(id='one')=>({
 id,symbol:'BTCUSDT',frame:'5m',direction:'LONG',status:'PENDING',
 entry:100,stop:95,targets:[105,110,115],target:115,
 createdAt:t,expiresAt:t+8*F,lastCandleTime:t,originalSignalId:'signal-1'
});
const book=()=>({version:1,mode:'manual',autoSince:0,orders:[]});
const candle=(i,lo,hi)=>({time:t+i*F,open:100,close:102,low:lo,high:hi,closed:true});
const markets=(bars,now,signal=null)=>({BTCUSDT:{price:104,lastTick:now,signals:signal?{'5m':signal}:{},candles:bars,frames:{}}});
let b=A.addManualDemo(book(),scenario(),t+100,100);
assert.equal(b.orders.length,1);
assert.equal(b.orders[0].status,'WAITING');
assert.deepEqual(b.orders[0].tpShares,[.4,.3,.3]);
assert.equal(A.addManualDemo(b,scenario(),t+200).orders.length,1,'manual duplicate blocked');
assert.equal(A.makeDemoLimit({...scenario(),status:'ACTIVE'},t),null,'no retroactive entry');
let o=A.advanceDemo(b.orders[0],markets([candle(1,99,104)],t+2*F).BTCUSDT,t+2*F);
assert.equal(o.status,'OPEN');assert.equal(o.tpReached,0,'do not award same-bar TP');
o=A.advanceDemo(o,markets([candle(2,101,105.5)],t+3*F).BTCUSDT,t+3*F);
assert.equal(o.tpReached,1);assert.equal(o.breakEven,true);assert.equal(o.effectiveStop,100);
assert.equal(o.remainingShare,.6);
assert.equal(o.grossPnl,2);
o=A.advanceDemo(o,markets([candle(3,99,109)],t+4*F).BTCUSDT,t+4*F);
assert.equal(o.status,'CLOSED');assert.equal(o.exit,'BREAK_EVEN');assert.equal(o.grossPnl,2);
let same=A.advanceDemo(b.orders[0],markets([candle(1,94,108)],t+2*F).BTCUSDT,t+2*F);
assert.equal(same.exit,'STOP');assert.equal(same.tpReached,0);
const expired=A.advanceDemo(b.orders[0],undefined,t+9*F);
assert.equal(expired.status,'EXPIRED');assert.equal(expired.activatedAt,undefined);
let rev=A.advanceDemo(b.orders[0],markets([candle(1,99,104)],t+2*F).BTCUSDT,t+2*F);
rev=A.advanceDemo(rev,markets([candle(2,101,106)],t+3*F).BTCUSDT,t+3*F);
const oppose={phase:'CONFIRMED',direction:'SHORT',candleTime:t+3*F,timestamp:t+4*F,id:'sig-short'};
rev=A.advanceDemo(rev,markets([],t+4*F,oppose).BTCUSDT,t+4*F);
assert.equal(rev.exit,'REVERSAL');
assert.equal(rev.status,'CLOSED');
assert.ok(rev.grossPnl>2);
const gap=A.advanceDemo(b.orders[0],markets([candle(4,99,110)],t+5*F).BTCUSDT,t+5*F);
assert.equal(gap.status,'NEEDS_REVIEW');
assert.equal(gap.exit,'DATA_GAP');
assert.equal(gap.grossPnl,0,'gaps must not invent PnL');
const auto=A.setAssistantMode(book(),'auto',t);
const older={...scenario('old'),createdAt:t-1};
const recent={...scenario('new'),createdAt:t+100};
const confirmation={phase:'CONFIRMED',direction:'LONG',id:'signal-1',timestamp:t+100,candleTime:t+100};
let ab=A.reconcileAssistant(auto,[older,recent],markets([],t+200,confirmation),t+200);
assert.equal(ab.orders.length,1,'only fresh scenarios');
assert.equal(ab.orders[0].origin,'auto');
assert.equal(A.reconcileAssistant(ab,[recent],markets([],t+250,confirmation),t+250).orders.length,1,'idempotent');
ab=A.setAssistantMode(ab,'manual',t+300);
assert.equal(ab.mode,'manual');
const serialized=JSON.stringify(ab);
assert.deepEqual(A.readAssistantBook(serialized),ab);
assert.equal(A.readAssistantBook('broken').mode,'manual','safe store recovery');
let closed=A.closeDemo(b,b.orders[0].id,t+2*F,undefined);
assert.equal(closed.orders[0].status,'CANCELLED');
assert.equal(closed.orders[0].activatedAt,undefined);
let stale=A.closeDemo({...b,orders:[rev.status==='CLOSED'?{...rev,status:'OPEN',remainingShare:.6}:rev]},rev.id,t+5*F,undefined);
assert.equal(stale.orders[0].status,'OPEN','do not invent a close at stale market price');
console.log('APEX 6.3 DEMO assistant PASS: manual/auto, staged TP, BE, expiry, adverse intrabar order, reversal, data gap, storage, no stale-price execution');
