const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),ts=require('typescript');
const source=fs.readFileSync('src/radar/watch.ts','utf8');
const out=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS}}).outputText;
const moduleObj={exports:{}};
vm.runInNewContext(out,{module:moduleObj,exports:moduleObj.exports,
 require:()=>({FRAME_DURATION:{'5m':300000,'1h':3600000,'4h':14400000}}),Date,Math,Object,Number,Array});
const {stabilizeWatch,restoreWatches}=moduleObj.exports;
const start=Date.UTC(2026,10,5,13,0),bar=300000;
const sample={id:'BTCUSDT:5m:LONG:WATCH:0',symbol:'BTCUSDT',direction:'LONG',phase:'WATCH',price:100.86,frame:'5m',level:101,invalidation:99,target:103,riskReward:1.3,volumeRatio:1,aggression:null,reason:'Observed level',timestamp:start,candleTime:start-bar};
const ctx=(now,price=100.86,candleTime=start-bar,close=100.1)=>({now,price,frame:'5m',rangeHigh:101,rangeLow:99,lastClosed:{time:candleTime,open:100,high:101,low:99,close,volume:100,closed:true},liveFresh:true});
let a=stabilizeWatch(null,sample,ctx(start));
assert.equal(a.signal?.watchState,'LIVE');
const episodeId=a.signal.id;
a=stabilizeWatch(a.memory,null,ctx(start+1000,100.61));
assert.equal(a.signal?.watchState,'HELD');
assert.equal(a.signal.id,episodeId);
a=stabilizeWatch(a.memory,{...sample,id:'raw id changed',candleTime:start},ctx(start+2000,100.84,start,100.3));
assert.equal(a.signal?.watchState,'LIVE');
assert.equal(a.signal.id,episodeId);
assert.equal(a.signal.timestamp,start);
const stale=stabilizeWatch(a.memory,null,{...ctx(start+3000),liveFresh:false});
assert.equal(stale.signal?.watchState,'STALE');
assert.equal(stale.signal.id,episodeId);
const invalid=stabilizeWatch(a.memory,null,ctx(start+bar*2,98.7,start+bar,98.8));
assert.equal(invalid.signal,null);
const confirmed=stabilizeWatch(a.memory,{...sample,phase:'CONFIRMED'},ctx(start+5000,101.2));
assert.equal(confirmed.signal?.phase,'CONFIRMED');
let far=stabilizeWatch(a.memory,null,ctx(start+5000,99.7));
assert.equal(far.signal?.watchState,'HELD');
far=stabilizeWatch(far.memory,null,ctx(start+bar+5001,99.7));
assert.equal(far.signal,null);
let quiet=stabilizeWatch(a.memory,null,ctx(start+1000,100.5));
quiet=stabilizeWatch(quiet.memory,null,ctx(start+3*bar+1001,100.5));
assert.equal(quiet.signal,null);
assert.equal(stabilizeWatch(a.memory,null,{...ctx(start+2000),rangeHigh:102.2}).signal,null);
const persisted=restoreWatches({'BTCUSDT:5m':a.memory},start+4000);
assert.equal(Object.keys(persisted).length,1);
assert.equal(Object.keys(restoreWatches(persisted,start+13*bar)).length,0);
const h4={...sample,frame:'4h',candleTime:start-14400000};
const long=stabilizeWatch(null,h4,{...ctx(start),frame:'4h'});
assert.ok(long.memory);
assert.ok(stabilizeWatch(long.memory,null,{...ctx(start+2*bar),frame:'4h'}).memory);
console.log('APEX WATCH: stable ID, noise, return, stale, invalidation, expiry, H4 tests passed');