assert.equal(e.shouldNotifyScenario({...s,status:'ACTIVE',tpReached:2},e.DEFAULT_STAGE_PREFS),false);
assert.equal(e.scenarioStageText({...s,status:'CANCELLED'}).body.includes('отменён'),true);
assert.equal(e.loadStagePrefs('bad').TP2,false);
assert.equal(e.loadStagePrefs('{"TP2":true}').TP2,true);
