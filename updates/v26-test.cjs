const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),ts=require('typescript');
const code=ts.transpileModule(fs.readFileSync('src/radar/stages.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const e={};vm.runInNewContext(code,{exports:e,JSON,Object,Array,Number,Math,String});
const s={id:'BTCUSDT:1h:SHORT:1793880000000',symbol:'BTCUSDT',frame:'1h',direction:'SHORT',status:'PENDING',entry:100,stop:104,targets:[96,93,90],target:90,tpReached:0};
const id=e.scenarioNotificationId(s.id);
assert.equal(id,e.scenarioNotificationId(s.id));
assert.equal(e.scenarioStage(s),'PENDING');
assert.equal(e.shouldNotifyScenario(s,e.DEFAULT_STAGE_PREFS),true);
assert.equal(e.scenarioStage({...s,status:'ACTIVE',tpReached:1}),'TP1');
