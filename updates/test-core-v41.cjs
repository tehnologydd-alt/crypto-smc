const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),ts=require('typescript');
const code=ts.transpileModule(fs.readFileSync('src/radar/research-core.ts','utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS}}).outputText;
const m={exports:{}};vm.runInNewContext(code,{module:m,exports:m.exports,require,Set});
const {CORE_ID,CORE_SYMBOLS,researchUniverse,coreLearning,isCoreSymbol}=m.exports;
assert.equal(CORE_ID,'fixed-core-v1');
assert.equal(CORE_SYMBOLS.length,5);
assert.equal(researchUniverse([]).length,5);
assert.equal(researchUniverse(['PEPEUSDT','BTCUSDT']).length,6);
assert.equal(researchUniverse(['BTCUSDT','SOLUSDT']).length,5);
assert.equal(isCoreSymbol('BTCUSDT'),true);
assert.equal(isCoreSymbol('PEPEUSDT'),false);
const rows=[{id:'old',cohort:undefined},{id:'fixed',cohort:'fixed-core-v1'},{id:'manual',cohort:undefined}];
const ledger={version:1,startedAt:100,records:rows};
const scoped=coreLearning(ledger);
assert.equal(scoped.records.length,1);
assert.equal(scoped.records[0].id,'fixed');
assert.equal(ledger.records.length,3,'original archive intact');
const freeze={version:1,frozenAt:300,trainingCutoff:200,expected:'with-pulse',trainingWeeks:[1,2,3]};
assert.equal(coreLearning({...ledger,corePulseHoldout:freeze}).pulseHoldout,freeze);
assert.equal(coreLearning({...ledger,pulseHoldout:freeze}).pulseHoldout,undefined,'legacy holdout excluded');
const app=fs.readFileSync('src/App.tsx','utf8');
assert(app.includes('feed.start(monitoredSymbols)'),'research symbols must receive live data');
assert(app.includes('reload(monitoredSymbols)'),'research symbols must load candles');
assert(app.includes('isCoreSymbol(asset.symbol)'),'fixed core generates paper scenarios');
assert(app.includes('reconcileLearning(prev,scenarios,cache.current,t,pulse,coreSince)'));
assert(!app.includes('reconcileLearning(prev,scenarios,assets,Date.now(),marketPulse)'));
assert(app.includes('coreLearning(learning)'));
assert(app.includes("favorites.includes(x.symbol)||savedDemoIds.has(x.id)"),'private core forecasts stay off personal Signals list');
console.log('APEX 4.1 independent research PASS (fixed universe, no favorite dependence, source isolation, legacy preserved)');
