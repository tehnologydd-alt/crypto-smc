const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm'),ts=require('typescript');
const output=ts.transpileModule(fs.readFileSync('src/radar/learning.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const m={exports:{}};vm.runInNewContext(output,{module:m,exports:m.exports,require,Date,Set,Map,Number,Math,JSON});
const {openLearning,reconcileLearning,learningOverview,wilson95}=m.exports;
const now=1_000_000,ledger=openLearning(null,now);
assert.equal(ledger.startedAt,now);
const old={id:'old',symbol:'BTCUSDT',frame:'1h',direction:'LONG',createdAt:now-1,status:'TARGET',entry:100,stop:95,target:112.5,lastCandleTime:now,reason:'old'};
const s={...old,id:'new',status:'PENDING',createdAt:now+1};
const market={BTCUSDT:{price:100,lastTick:now+1,volumeRatio:1.4,signals:{'5m':{phase:'CONFIRMED',direction:'LONG'},'1h':{phase:'CONFIRMED',direction:'LONG'},'4h':{phase:'CONFIRMED',direction:'SHORT'}}}};
const one=reconcileLearning(ledger,[old,s],market,now+2);
assert.equal(one.records.length,1);
assert.equal(one.records[0].initialVotes['4h'],'SHORT');
assert.equal(one.records[0].initialVotes['5m'],'LONG');
assert.equal(learningOverview(one).conflicted.total,1);
assert.equal(reconcileLearning(one,[s],market,now+2),one,'Stable record should not trigger re-render');
const done={...s,status:'STOP',tpReached:1,lastCandleTime:now+300000,closedAt:now+300000};
const two=reconcileLearning(one,[done],{},now+300001);
assert.equal(two.records[0].tpReached,1);
assert.equal(learningOverview(two).overall.stops,1);
assert.equal(learningOverview(two).overall.tp1,1);
assert.equal(learningOverview(two).overall.targets,0);
assert.equal(learningOverview(two).overall.credible,false);
const outdated={...s,id:'background',createdAt:now+50};
const three=reconcileLearning(two,[outdated],{},now+500000);
assert.equal(three.records.find(x=>x.id==='background').contextCaptured,false);
assert.equal(learningOverview(three).unknown.total,1);
const conf=wilson95(15,30);assert(conf[0]>0&&conf[1]<100);assert.equal(wilson95(2,0),null);
const restored=openLearning(JSON.stringify(three),now+900000);
assert.equal(restored.records.length,2);
console.log('APEX Learning Engine tests PASS (legacy exclusion, immutable snapshot, TP1 then stop, uncertainty)');
