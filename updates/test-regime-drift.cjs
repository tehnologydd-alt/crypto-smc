const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),ts=require('typescript');
const src=fs.readFileSync('src/radar/regime-drift.ts','utf8');
const js=ts.transpileModule(src,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const m={exports:{}};vm.runInNewContext(js,{module:m,exports:m.exports,require,Number,Math,Set,Map,Date,JSON,Array});
const D=m.exports,H=3600000,DAY=24*H,t=Date.UTC(2026,9,1,0),registration=t;
const frozenAt=t-H,subject={protocol:'core-h1-holdout-v1',frozenAt,registeredAt:t-2*H,
 from:'up',expected:'up',trainingCount:35,trainingMatches:30,trainingDays:5,lastTrainingToAt:frozenAt};
const holdout=outcomes=>({version:1,frozen:subject,outcomes,watermark:outcomes.at(-1)?.toAt||frozenAt});
const event=(hours,to)=>({fromAt:t+hours*H,toAt:t+(hours+1)*H,from:'up',to});
const early=Array.from({length:20},(_,i)=>event(1+i*4,'up'));
const latest=Array.from({length:25},(_,i)=>event(84+i*4,'down'));
let ledger=D.openDriftLedger(null,t);
assert.equal(ledger.registeredAt,t);
assert.equal(D.advanceDriftLedger(ledger,holdout([]),t),ledger===null?null:ledger===undefined?undefined:D.advanceDriftLedger(ledger,holdout([]),t),'deterministic initialization not required same object');
const first=D.advanceDriftLedger(ledger,holdout(early.slice(0,19)),t+80*H);
assert.equal(first.anchor,undefined,'no baseline before 20 observations');
assert.equal(first.collecting.length,19);
const firstDone=D.advanceDriftLedger(first,holdout(early),t+80*H);
assert.equal(firstDone.anchor.count,20);
assert.equal(firstDone.anchor.matches,20);
assert(firstDone.anchor.days>=3);
assert.equal(firstDone.collecting.length,0);
assert.equal(firstDone.recent.length,0,'baseline samples cannot be future');
const repeat=D.advanceDriftLedger(firstDone,holdout(early),t+81*H);
assert.equal(repeat,firstDone,'re-ingestion does not duplicate');
const later=D.advanceDriftLedger(firstDone,holdout([...early,...latest]),t+185*H);
assert.equal(later.anchor,firstDone.anchor,'immutable early reference');
assert.equal(later.recent.length,25);
const report=D.driftReport(later,t+185*H);
assert.equal(report.phase,'possible-decline','large sustained drop raises research concern');
assert.equal(report.baselinePct,100);
assert.equal(report.recentPct,0);
assert(report.recentDays>=3);
assert.equal(report.differencePct,100);
const resumed=D.openDriftLedger(JSON.stringify(later),t+185*H);
assert.equal(resumed.anchor.count,20);
assert.equal(resumed.recent.length,25);
assert.equal(D.advanceDriftLedger(resumed,holdout([...early,...latest]),t+186*H),resumed,'restart replay rejected');
const wrongHypo={...subject,expected:'down'};
assert.equal(D.advanceDriftLedger(later,{...holdout([...early,...latest]),frozen:wrongHypo},t+185*H),later,'no silent reset when frozen hypothesis changes');
const future=event(280,'down');
assert.equal(D.advanceDriftLedger(later,holdout([...early,...latest,future]),t+185*H),later,'future outcomes excluded');
const stale=D.driftReport(later,t+280*H);
assert.equal(stale.phase,'observations-stale','old pattern status must not claim current reliability');
const same=Array.from({length:25},(_,i)=>event(84+i*4,'up'));
const stable=D.advanceDriftLedger(firstDone,holdout([...early,...same]),t+185*H);
assert.equal(D.driftReport(stable,t+185*H).phase,'no-clear-decline');
const tooFew=D.advanceDriftLedger(firstDone,holdout([...early,...latest.slice(0,9)]),t+130*H);
assert.equal(D.driftReport(tooFew,t+130*H).phase,'collecting-recent');
const twoDays=Array.from({length:22},(_,i)=>event(84+i,'down'));
const cluster=D.advanceDriftLedger(firstDone,holdout([...early,...twoDays]),t+111*H);
assert.equal(D.driftReport(cluster,t+111*H).phase,'collecting-recent','many adjacent samples on two days are not enough');
const dup=[...early,...latest,{...latest[0],to:'up'}];
const repeated=D.advanceDriftLedger(firstDone,holdout(dup),t+185*H);
assert.equal(repeated.recent.length,25,'duplicate closed hours counted only once');
const prior=event(-8,'down');
assert.equal(D.advanceDriftLedger(ledger,holdout([prior]),t+3*H).collecting.length,0,'no backfill prior to 4.7 registration');
assert.equal(D.driftReport(ledger,t).phase,'awaiting-hypothesis');
assert.equal(D.wilson90(50,20),null);
assert(D.wilson90(20,20)[0]>0.8);
const app=fs.readFileSync('src/App.tsx','utf8');
assert(app.includes('openDriftLedger'));
assert(app.includes('advanceDriftLedger(prev,hourHoldout'));
assert(app.includes('driftReport(driftLedger,now)'));
assert(app.includes('Устойчивость · 4.7'));
assert(app.includes("label:'Статистика'"));
assert(!fs.readFileSync('src/radar/learning.ts','utf8').includes('advanceDriftLedger'));
console.log('APEX 4.7 drift PASS: 3-day anchored baseline, strictly prospective outcomes, replay guard, 7-day recent window, stale detection, conservative change flag');
