const assert=require('node:assert/strict'),fs=require('node:fs'),ts=require('typescript'),vm=require('node:vm');
const code=ts.transpileModule(fs.readFileSync('src/radar/hour-holdout.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const m={exports:{}};vm.runInNewContext(code,{module:m,exports:m.exports,require,Date,Number,Math,Set,Map,Array,JSON});
const H=m.exports,HR=3600000,DAY=24*HR,t=Date.UTC(2026,10,6,13);
const since=t-5*DAY;
const edges=[];
const types=['up','down','mixed'];
for(let i=0;i<75;i++){
 const from=types[i%3],to=from==='up'?'up':from==='down'?'mixed':'up';
 const fromAt=since+HR+i*HR,toAt=fromAt+HR;
 edges.push({fromAt,toAt,from,to});
}
const empty={version:1,outcomes:[],watermark:0};
assert.equal(H.advanceHourHoldout(empty,edges.slice(0,12),since,t),empty,'tiny samples must not freeze');
const freezingAt=since+100*HR;
let frozen=H.advanceHourHoldout(empty,edges,since,freezingAt);
assert(frozen.frozen,'training eligible');
assert.equal(frozen.frozen.trainingCount,25);
assert.equal(frozen.frozen.trainingDays>=3,true);
assert.equal(frozen.frozen.expected,'up');
assert.equal(frozen.frozen.from,'up');
assert.equal(frozen.outcomes.length,0,'no in-sample validation');
assert.equal(frozen.watermark,freezingAt);
const validation=[];
for(let j=0;j<30;j++){
 const fromAt=freezingAt+HR+j*HR;
 validation.push({fromAt,toAt:fromAt+HR,from:types[j%3],to:types[j%3]==='up'?'up':'mixed'});
}
const cutoff=freezingAt+40*HR;
const after=H.advanceHourHoldout(frozen,[...edges,...validation],since,cutoff);
assert.equal(after.outcomes.length,30);
assert.equal(after.outcomes.filter(e=>e.from==='up').length,10);
assert.equal(after.outcomes.some(e=>e.fromAt<=freezingAt),false,'no training leakage');
assert.equal(H.advanceHourHoldout(after,validation,since,cutoff),after,'no duplicates on re-ingest');
const parsed=H.openHourHoldout(JSON.stringify(after),cutoff);
assert.equal(parsed.outcomes.length,30);
assert.equal(parsed.watermark,after.watermark);
let report=H.hourHoldoutReport(parsed,validation,since,cutoff);
assert.equal(report.frozen,true);assert.equal(report.futureEdges,10);assert.equal(report.conditionEdges,30);
assert.equal(report.futureMatched,10);assert.equal(report.futurePct,100);
assert.equal(report.baselineMatched,10);
assert.equal(report.baselinePct,33.3);
assert.equal(report.status,'collecting-future','10 condition instances below 20');
const corrupt=H.openHourHoldout(JSON.stringify({...after,frozen:{...after.frozen,expected:'surprise'}}),cutoff);
assert.equal(corrupt.frozen,undefined);
const rewound=H.advanceHourHoldout(after,[{fromAt:after.watermark-2*HR,toAt:after.watermark-HR,from:'up',to:'mixed'}],since,cutoff);
assert.equal(rewound,after,'late replay ignored');
const next=H.advanceHourHoldout(after,[{fromAt:cutoff+HR,toAt:cutoff+2*HR,from:'up',to:'down'}],since,cutoff+3*HR);
assert.equal(next.outcomes.length,31);assert.equal(next.outcomes.at(-1).to,'down');
assert.equal(next.frozen.frozenAt,frozen.frozen.frozenAt,'freeze immutable');
const none=H.hourHoldoutReport(empty,edges.slice(0,5),since,t);
assert.equal(none.status,'collecting-training');
assert.equal(none.trainingCount,0);
const app=fs.readFileSync('src/App.tsx','utf8');
assert(app.includes("openHourHoldout(localStorage.getItem('apex_v46_holdout')"));
assert(app.includes('advanceHourHoldout(prev,transitionStats.evidence'));
assert(app.includes('hourHoldoutReport(hourHoldout,transitionStats.evidence'));
assert(app.includes('Вневыборочная проверка · 4.6'));
assert(!fs.readFileSync('src/radar/learning.ts','utf8').includes('advanceHourHoldout'));
console.log('APEX 4.6 holdout PASS: immutable freeze, forward-only evidence, unique transitions, baseline, no Learning contamination');
