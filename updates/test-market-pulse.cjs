const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),ts=require('typescript');
const js=ts.transpileModule(fs.readFileSync('src/radar/market-pulse.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const mod={exports:{}};vm.runInNewContext(js,{module:mod,exports:mod.exports,require,Date,Map,Math,Number});
const {summarizePulse,evaluatePulseAsset}=mod.exports;
const now=20_000_000_000;
const frames=['5m','1h','4h'];
const quality=(state='ok')=>({level:state,tickFresh:state!=='bad',
 frames:Object.fromEntries(frames.map(f=>[f,{status:state==='warning'&&f==='4h'?'gaps':'ok'}]))});
const sig=(symbol,frame,direction,phase='CONFIRMED',age=120000)=>({symbol,frame,phase,direction,candleTime:now-age});
const asset=(symbol,votes,tick=now-1500)=>({symbol,price:100,lastTick:tick,signals:Object.fromEntries(Object.entries(votes).map(([f,v])=>[f,v?sig(symbol,f,v):null]))});
const a=asset('BTCUSDT',{'5m':'LONG','1h':'LONG','4h':null});
const b=asset('ETHUSDT',{'5m':'SHORT','1h':'SHORT','4h':null});
const c=asset('SOLUSDT',{'5m':'LONG','1h':'SHORT'});
const d=asset('XRPUSDT',{'5m':'LONG'});
const e=asset('ADAUSDT',{});
const bad=asset('DOGEUSDT',{'5m':'LONG','1h':'LONG'},now-180000);
const items=[a,b,c,d,e,bad];
const qualities=Object.fromEntries(items.map(x=>[x.symbol,quality()]));
let r=summarizePulse(items,qualities,now);
assert.equal(r.watched,6);assert.equal(r.eligible,5);
assert.equal(r.bullish,1);assert.equal(r.bearish,1);assert.equal(r.conflict,1);
assert.equal(r.partial,1);assert.equal(r.quiet,1);assert.equal(r.unavailable,1);
assert.equal(r.title,'Смешанная картина');
assert.equal(summarizePulse([a,a],qualities,now).watched,1,'no double counting');
assert.equal(evaluatePulseAsset(a,quality('bad'),now).category,'unavailable');
assert.equal(evaluatePulseAsset(a,quality('warning'),now).category,'bullish');
const old=asset('TRXUSDT',{'5m':'LONG','1h':'LONG'});
old.signals['5m'].candleTime=now-1900000;old.signals['1h'].candleTime=now-9000000;
assert.equal(evaluatePulseAsset(old,quality(),now).category,'quiet','stale signal cannot vote');
const mis=asset('LINKUSDT',{'5m':'LONG','1h':'LONG'});
mis.signals['1h'].symbol='OTHER';
assert.equal(evaluatePulseAsset(mis,quality(),now).category,'partial','wrong symbol blocked');
assert.equal(summarizePulse([],{},now).title,'Нет избранных активов');
assert.equal(summarizePulse([a,b],qualities,now).title,'Мало данных для общего вывода');
const trend=['BTCUSDT','ETHUSDT','SOLUSDT'].map(s=>asset(s,{'5m':'LONG','1h':'LONG'}));
r=summarizePulse(trend,Object.fromEntries(trend.map(x=>[x.symbol,quality()])),now);
assert.equal(r.title,'Больше подтверждений роста');
console.log('APEX 3.5 Market Pulse tests PASS: favorites only, freshness, conflicts, partial, no duplicates');
